BASE_X = 220
INCREMENT = 16

class Piece:
    def __init__(self, name:str, board:Board, x:int, y:int, team:Team, crucial:bool=False, direction:int=1, icon = ""):
        self.name:str = name
        self.board:Board = board
        self.moves:list[Move] = []
        self.possible_moves:list[list] = []
        self.x:int = x
        self.y:int = y
        self.times_moved:int = 0
        self.team:Team = team
        self.crucial:bool = crucial
        self.direction:int = direction

        # Arcade
        self.icon = arcade.Sprite(arcade.load_texture(icon))
        self.icon.center_x = (x * INCREMENT) + BASE_X
        self.icon.center_y = (y * INCREMENT) + BASE_Y

